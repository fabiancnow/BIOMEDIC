-- ============================================================================
-- BIOMEDIC CENTRO MÉDICO — Esquema PostgreSQL + Supabase Auth
-- Tabla obligatoria de la rúbrica: public.leads
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.leads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    nombre_completo TEXT NOT NULL,
    correo_electronico TEXT NOT NULL,
    whatsapp TEXT NOT NULL,
    empresa_negocio TEXT NOT NULL,
    presupuesto_estimado TEXT NOT NULL,
    dolor_principal TEXT NOT NULL,
    especialidad_servicio TEXT,
    fecha_cita DATE,
    hora_cita TEXT,
    modalidad_atencion TEXT DEFAULT 'Presencial en Sede BioMedic (Cuenca)',
    estado_lead TEXT DEFAULT 'Pre-calificado / Cita Reservada',
    dispositivo_origen TEXT
);

-- Habilitar Row Level Security (RLS)
ALTER TABLE public.leads ENABLE ROW LEVEL SECURITY;

-- 1. Política para permitir inserción desde la Landing Page (tanto visitantes anon como usuarios autenticados con Supabase Auth)
DROP POLICY IF EXISTS "Permitir insercion publica de leads BIOMEDIC" ON public.leads;
CREATE POLICY "Permitir insercion publica de leads BIOMEDIC"
ON public.leads
FOR INSERT
TO anon, authenticated
WITH CHECK (true);

-- 2. Política para permitir lectura de leads/citas en el Panel de Control y Portal del Paciente
DROP POLICY IF EXISTS "Permitir lectura publica de leads BIOMEDIC" ON public.leads;
CREATE POLICY "Permitir lectura publica de leads BIOMEDIC"
ON public.leads
FOR SELECT
TO anon, authenticated
USING (true);

-- 3. Política para permitir que usuarios autenticados (Recepción / Doctores) actualicen el estado de una cita
DROP POLICY IF EXISTS "Permitir actualizacion a usuarios autenticados BIOMEDIC" ON public.leads;
CREATE POLICY "Permitir actualizacion a usuarios autenticados BIOMEDIC"
ON public.leads
FOR UPDATE
TO authenticated
USING (true)
WITH CHECK (true);
